type pendingLaunch struct {
	ID       uint64
	Count    int
	Until    time.Time
	Baseline map[string]bool
	Panes    map[string]bool
}
type admission struct {
	app *App
	id  uint64
}

func agentIdentity(p Pane) string { return p.ID + "|" + p.Name + "|" + p.Agent }

// reconcilePendingLocked consumes each newly observed agent at most once. Cached
// screens and metadata errors never confirm a launch; only a successful snapshot does.
func (a *App) reconcilePendingLocked(state State) {
	now := time.Now()
	claimed := map[string]bool{}
	kept := a.pending[:0]
	for _, p := range a.pending {
		if !now.Before(p.Until) {
			continue
		}
		for _, pane := range state.Panes {
			identity := agentIdentity(pane)
			if pane.Agent == "" || p.Baseline[identity] || claimed[identity] {
				continue
			}
			if len(p.Panes) > 0 && !p.Panes[pane.ID] {
				continue
			}
			if p.Count > 0 {
				p.Count--
				claimed[identity] = true
				p.Baseline[identity] = true
			}
		}
		if p.Count > 0 {
			kept = append(kept, p)
		}
	}
	a.pending = kept
}

func (a *App) admit(ctx context.Context, plan []paneRequest) (*admission, error) {
	if len(plan) == 0 {
		return &admission{}, nil
	}
	// Serialize policy checking with reservations even for callers outside lockedWrite.
	a.admissionMu.Lock()
	defer a.admissionMu.Unlock()
	snapshot, err := a.currentSnapshot(ctx)
	if err != nil {
		return nil, err
	}
	for i := range plan {
		p := &plan[i]
		if p.Profile == "next" {
			usage, e := a.herdr.Helper(ctx, map[string]string{"Command": "usage"})
			if e != nil {
				return nil, e
			}
			account, e := pickNextAccount(usage, a.lead.Account)
			if e != nil {
				return nil, e
			}
			p.Profile = "claude"
			p.Account = account
		}
		if _, ok := a.profiles[p.Profile]; !ok {
			return nil, fmt.Errorf("unknown launch profile %q", p.Profile)
		}
		if err := a.launchGuard(*p); err != nil {
			return nil, err
		}
	}
	a.mu.Lock()
	defer a.mu.Unlock()
	a.initGuardsLocked()
	a.reconcilePendingLocked(snapshot)
	active := 0
	baseline := map[string]bool{}
	for _, p := range snapshot.Panes {
		if p.Agent != "" {
			active++
			baseline[agentIdentity(p)] = true
		}
	}
	for _, p := range a.pending {
		active += p.Count
	}
	if active+len(plan) > a.guards.Policy.MaxActive {
		return nil, &statusError{Status: 409, Msg: "capacity", Fields: map[string]any{"message": fmt.Sprintf("%d live/pending agents plus %d requested exceed the limit %d", active, len(plan), a.guards.Policy.MaxActive)}}
	}
	a.launchSequence++
	a.pending = append(a.pending, &pendingLaunch{ID: a.launchSequence, Count: len(plan), Until: time.Now().Add(120 * time.Second), Baseline: baseline})
	for _, p := range plan {
		if folder := a.launchFolder(p); folder != "" {
			a.launchFolders[filepath.VolumeName(folder)+`\`] = true
		}
	}
	return &admission{app: a, id: a.launchSequence}, nil
}

func (ticket *admission) finish(output string, err error) {
	if ticket == nil || ticket.app == nil {
		return
	}
	a := ticket.app
	a.mu.Lock()
	defer a.mu.Unlock()
	for i, p := range a.pending {
		if p.ID == ticket.id {
			if err != nil {
				a.pending = append(a.pending[:i], a.pending[i+1:]...)
				return
			}
			ids := startedIdentities(output)
			if len(ids) > 0 {
				p.Panes = map[string]bool{}
				for _, id := range ids {
					p.Panes[id["pane_id"]] = true
				}
			}
			return
		}
	}
}

var startedLine = regexp.MustCompile(`(?m)^STARTED\s+[^\r\n]*`)
var startedName = regexp.MustCompile(`(?:^|\s)name=([^\s]+)`)
var startedPane = regexp.MustCompile(`(?:^|\s)pane=([^\s]+)`)

func startedIdentities(output string) []map[string]string {
	found := []map[string]string{}
	for _, line := range startedLine.FindAllString(output, -1) {
		name, pane := startedName.FindStringSubmatch(line), startedPane.FindStringSubmatch(line)
		if len(name) == 2 && len(pane) == 2 {
			found = append(found, map[string]string{"name": name[1], "pane_id": pane[1]})
		}
	}
	return found
}

// Expand only fixed, known script adapters, before any script can start agents.
func (a *App) scriptLaunchPlan(script string, params map[string]any) ([]paneRequest, error) {
	plan := []paneRequest{}
	str := func(key string) string { value, _ := params[key].(string); return value }
	switch script {
	case "herdr-open-folder.ps1":
		names := []string{str("Agent")}
		if names[0] == "team" {
			names = []string{"claude", "codex"}
		}
		for _, name := range names {
			if name != "" {
				plan = append(plan, paneRequest{Profile: name, Cwd: str("Path")})
			}
		}
	case "herdr-layout.ps1", "herdr-agents.ps1":
		if script == "herdr-agents.ps1" && str("Command") != "team" {
			return plan, nil
		}
		path := str("PlanFile")
		// Plans are generated by the Deck, never arbitrary path readers.
		base := filepath.Join(os.Getenv("APPDATA"), "herdr", "deck-plans")
		rel, err := filepath.Rel(base, path)
		if err != nil || strings.HasPrefix(rel, "..") {
			return nil, fmt.Errorf("launch plan outside Deck plans")
		}
		text, err := readAllowed(base, rel)
		if err != nil {
			return nil, err
		}
		if script == "herdr-layout.ps1" {
			var layout LayoutPlan
			if err = json.Unmarshal([]byte(text), &layout); err != nil {
				return nil, err
			}
			for _, c := range layout.Columns {
				if c.Type == "new" {
					plan = append(plan, paneRequest{Profile: c.Value, Model: c.Model, Account: c.Account, Cwd: c.Folder})
				}
			}
		} else {
			var team struct {
				Agents []struct{ Agent, Cwd, Account, Model string }
			}
			if err = json.Unmarshal([]byte(text), &team); err != nil {
				return nil, err
			}
			for _, member := range team.Agents {
				plan = append(plan, paneRequest{Profile: member.Agent, Cwd: member.Cwd, Account: member.Account, Model: member.Model})
			}
		}
	case "herdr-headless.ps1", "herdr-trial.ps1":
		plan = append(plan, paneRequest{Profile: str("AgentProfile"), Cwd: str("Cwd"), Account: str("Account")})
	}
	return plan, nil
}

func (a *App) launchFolder(p paneRequest) string {
	worktree := false
	switch value := p.Worktree.(type) {
	case bool:
		worktree = value
	case string:
		worktree = value != ""
	}
	if worktree {
		return filepath.Join(os.Getenv("USERPROFILE"), ".herdr", "worktrees")
	}
	if p.Cwd != "" {
		return p.Cwd
	}
	return a.root
}
